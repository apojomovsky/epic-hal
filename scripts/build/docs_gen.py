#!/usr/bin/env python3
"""Generate the HAL reference pages, the user module pages and README.md.

The reference pages are data, not prose: docs/reference/modules.md and
docs/reference/families.md render common/manifest/modules.toml, so a new
module or family shows up without anyone editing a doc. README.md renders
from docs/README.src.md with every `--8<-- "path"` include expanded (GitHub
shows README.md as-is, so includes resolve at generation time, not view
time). docs/user/ holds the user-facing HAL module index and one page
per library module (`lib/*`), also rendered from the manifest, for the
epic-docs hub. `make docs-gen` runs this; `--check` fails without writing, and
the CI docs job runs it so a stale generated page fails the build.
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import bundlegen  # noqa: E402
import epicmanifest  # noqa: E402
import readme_tables  # noqa: E402
import shared_includes  # noqa: E402

GENERATED_BY = "scripts/build/docs_gen.py"

# Core names keyed by the arch segment of a family's hal_dir
# (hal/<arch>/<family>). A new arch fails loudly here instead of
# rendering a wrong core, so the mapping stays deliberate.
_CORE_BY_ARCH = {
    "pic12": "PIC12 baseline",
    "pic14": "PIC14 (mid-range)",
    "pic14e": "PIC14E (enhanced mid-range)",
    "pic18": "PIC18",
}

# One include per line: `--8<-- "path"`, path repo-root-relative.
_INCLUDE_RE = re.compile(r'^([ \t]*)--8<--\s+"([^"]+)"\s*$')


class DocsGenError(Exception):
    """A generated page whose inputs do not resolve."""


def module_id(mod) -> str:
    """The reference index entry for one module.

    Prefers an `id` field when the manifest carries one (epic-hal#308
    derives ids from the path) and falls back to the table key, so the
    generator survives the id migration either way.
    """
    return getattr(mod, "id", None) or mod.name


def core_of(hal_dir: str) -> str:
    """The core name for a family hal_dir of the form hal/<arch>/<family>."""
    try:
        arch = hal_dir.split("/")[1]
        return _CORE_BY_ARCH[arch]
    except (IndexError, KeyError):
        raise DocsGenError(
            f"hal_dir {hal_dir!r} names no known arch;"
            " extend _CORE_BY_ARCH") from None


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def emit_modules_md(manifest: epicmanifest.Manifest) -> str:
    """The module index: id, manifest summary, families supported."""
    lines = [
        f"<!-- Generated by {GENERATED_BY}, do not edit. -->",
        "# HAL module index",
        "",
        "Every module in the manifest, with its one-line summary and the"
        " families it supports.",
        "",
        "| Module | Summary | Families |",
        "|---|---|---|",
    ]
    for name in sorted(manifest.modules):
        mod = manifest.modules[name]
        fams = ", ".join(sorted(mod.supported))
        lines.append(f"| `{module_id(mod)}`"
                     f" | {_cell(mod.summary)} | {_cell(fams)} |")
    return "\n".join(lines) + "\n"


def emit_families_md(manifest: epicmanifest.Manifest) -> str:
    """One fact section per family: parts, core, modules, simulator."""
    lines = [
        f"<!-- Generated by {GENERATED_BY}, do not edit. -->",
        "# HAL family facts",
        "",
        "Per-family facts from the manifest: parts, core, modules"
        " available, simulator support, and any documented MPLAB-SIM"
        " limit.",
        "",
    ]
    for name in sorted(manifest.families):
        fam = manifest.families[name]
        mods = sorted(m for m in manifest.modules
                      if name in manifest.modules[m].supported)
        sim = any(entry.sim is not None
                  for m in mods
                  for _, entry in manifest.examples_for(m, name))
        lines += [
            f"## {name}",
            "",
            "| Fact | Value |",
            "|---|---|",
            f"| Parts | {_cell(', '.join(fam.variants))} |",
            f"| Core | {_cell(core_of(fam.hal_dir))} |",
            f"| Modules | {_cell(', '.join(f'`{m}`' for m in mods))} |",
            f"| Simulator | {'MDB sim gate' if sim else 'Target only'} |",
            f"| Simulator limits |"
            f" {_cell(fam.sim_note or 'None documented')} |",
            "",
        ]
    return "\n".join(lines).rstrip("\n") + "\n"


USER_DIR = "docs/user"
REPO_URL = "https://github.com/apojomovsky/epic-hal"
# Module trees that get a user page. hal/ ports are covered by the family
# facts, demos/ and tests/ are firmware, not modules a project links.
_USER_TREES = ("lib/",)


def user_modules(manifest: epicmanifest.Manifest) -> list[str]:
    """Manifest names of the modules that get a user page, sorted."""
    return sorted(n for n, m in manifest.modules.items()
                  if module_id(m).startswith(_USER_TREES))


def _page_name(mod) -> str:
    return module_id(mod).split("/", 1)[1]


def _pic(part: str) -> str:
    """A manifest part spelled as Microchip does (16F877A to PIC16F877A)."""
    return part if part.startswith("PIC") else f"PIC{part}"


def _sentence(text: str) -> str:
    text = text.strip()
    return text if text.endswith((".", "!", "?")) else text + "."


def _has_sim(manifest, mod, fam: str) -> bool:
    return any(entry.sim is not None
               for _, entry in manifest.examples_for(mod.name, fam))


def emit_user_index_md(manifest: epicmanifest.Manifest) -> str:
    """The user-facing module index: one row per library module."""
    lines = [
        f"<!-- Generated by {GENERATED_BY}, do not edit. -->",
        "# HAL modules",
        "",
        "This page lists the HAL modules you can add to a firmware project,"
        " with what each does and the families it supports. Open a module"
        " for its fact box, limits and where to find its example.",
        "",
        "| Module | What it does | Families |",
        "|---|---|---|",
    ]
    for name in user_modules(manifest):
        mod = manifest.modules[name]
        fams = ", ".join(sorted(mod.supported))
        lines.append(f"| [`{module_id(mod)}`](modules/{_page_name(mod)}.md)"
                     f" | {_cell(mod.summary)} | {_cell(fams)} |")
    return "\n".join(lines) + "\n"


def emit_user_module_md(manifest: epicmanifest.Manifest, name: str) -> str:
    """One module page, following epic-docs templates/hal-module.md.tmpl.

    Every fact comes from the manifest. The template's tested-example and
    hand-written API sections are not in the manifest, so the page points
    at the example source and the module directory instead of inventing
    prose.
    """
    mod = manifest.modules[name]
    mid = module_id(mod)
    fams = sorted(mod.supported)
    users = sorted(
        module_id(m) for n, m in manifest.modules.items()
        if name in m.depends_on and module_id(m).startswith(_USER_TREES))

    def mod_link(dep: str) -> str:
        dm = manifest.modules[dep]
        if module_id(dm).startswith(_USER_TREES):
            return f"[`{module_id(dm)}`]({_page_name(dm)}.md)"
        return f"`{module_id(dm)}`"

    lines = [
        f"<!-- Generated by {GENERATED_BY}, do not edit. -->",
        f"# {mid} module",
        "",
        f"{_sentence(mod.summary)} This page is the reference for the"
        f" `{mid}` HAL module, for firmware authors choosing and"
        " wiring it in.",
        "",
        "## Fact box",
        "",
        "| Fact | Value |",
        "|---|---|",
        f"| Module id | `{mid}` |",
        f"| Source | [`{mod.dir}`]({REPO_URL}/tree/master/{mod.dir}) |",
        f"| Families | {_cell(', '.join(fams) or 'None')} |",
    ]
    for fam in fams:
        lines.append(f"| Parts, {fam} |"
            f" {_cell(', '.join(_pic(p) for p in mod.supported[fam]))} |")
    srcs = [epicmanifest.join_module_path(mod.dir, p) for p in mod.sources]
    lines += [
        f"| Source files | {_cell(', '.join(f'`{p}`' for p in srcs))} |",
        "| Depends on | "
        + (", ".join(mod_link(d) for d in mod.depends_on) or "Nothing")
        + " |",
        "| Used by | "
        + (", ".join(mod_link(manifest.resolve_module(u).name)
                     for u in users) or "No other module")
        + " |",
        f"| Needs a family HAL | {'Yes' if mod.needs_hal else 'No'} |",
    ]
    sim = [f for f in fams if _has_sim(manifest, mod, f)]
    lines.append("| Simulator gate | "
                 + (_cell(", ".join(sim)) if sim else "None") + " |")
    notes = [f"{f}: {manifest.families[f].sim_note}" for f in fams
             if f in manifest.families and manifest.families[f].sim_note]
    lines += [
        "| Simulator limits | "
        + (_cell("; ".join(notes)) if notes else "None documented") + " |",
        "",
        "## Use it",
        "",
    ]
    ex_rows = []
    for fam in fams:
        for ex_id, ex in manifest.examples_for(mod.name, fam):
            paths = [epicmanifest.join_module_path(mod.dir, p)
                     for p in ex.sources]
            links = ", ".join(f"[`{p}`]({REPO_URL}/blob/master/{p})"
                              for p in paths)
            label = fam if ex_id is None else f"{fam} ({ex_id})"
            ex_rows.append(f"| {label} | `{ex.name}` | {links} |")
    if ex_rows:
        lines += [
            "The manifest lists one example program per family, plus peer"
            " programs for extra transports where the driver has them."
            " Build one with the repository build driver (--example names"
            " a peer), or read it as the working starting point for your"
            " own firmware.",
            "",
            "| Family | Example | Source |",
            "|---|---|---|",
            *ex_rows,
        ]
    else:
        lines.append("No example program is listed in the manifest for this"
                     " module, so there is no example to link yet.")
    lines += [
        "",
        "## API",
        "",
    ]
    if mod.functions:
        lines += [
            f"The API is documented next to the code, in the"
            f" [`{mid}` directory]({REPO_URL}/tree/master/{mod.dir}). This"
            " page does not restate it.",
            "",
            "The manifest lists these public functions:",
            "",
            "| Function |",
            "|---|",
            *(f"| `{f}` |" for f in mod.functions),
            "",
        ]
    else:
        lines += [
            f"The API is documented next to the code, in the"
            f" [`{mid}` directory]({REPO_URL}/tree/master/{mod.dir}). This"
            " page does not restate it. The manifest carries no function list,"
            " so no API table is generated here yet.",
            "",
        ]
    lines += [
        "## Limits",
        "",
    ]
    reasons: dict[str, list[str]] = {}
    for part, why in mod.excluded.items():
        reasons.setdefault(why, []).append(part)
    for why in sorted(reasons):
        parts = ", ".join(_pic(p) for p in sorted(reasons[why]))
        lines.append(f"- Not built for {parts}. Reason: {why}.")
    for note in notes:
        lines.append(f"- Simulator: {note}.")
    if not reasons and not notes:
        lines.append("- No limits are recorded in the manifest.")
    lines += [
        "",
        "## Related",
        "",
        "- [All HAL modules](../index.md)",
    ]
    return "\n".join(lines) + "\n"


def emit_packs_md(manifest: epicmanifest.Manifest) -> str:
    """The XC8 device packs and release bundles, one table per concern.

    Rows come from the same helpers the README docgen blocks use, so the
    page and the README cannot list different packs or bundles."""
    lines = [
        f"<!-- Generated by {GENERATED_BY}, do not edit. -->",
        "# XC8 device packs and release bundles",
        "",
        "Every family's XC8 device pack, with the Microchip download, and"
        " every release bundle with the parts it carries. Install the pack"
        " as described in [getting started](../getting-started.md#xc8-device-packs).",
        "",
        "## Device packs",
        "",
        "| Family | Pack | Download |",
        "|---|---|---|",
    ]
    for name, pack, url in bundlegen.pack_rows(manifest):
        lines.append(f"| {_cell(name)} | `{_cell(pack)}` | <{url}> |")
    lines += [
        "",
        "## Release bundles",
        "",
        "| Bundle | Parts inside |",
        "|---|---|",
    ]
    for archive, parts in bundlegen.bundle_rows(manifest):
        lines.append(f"| `{_cell(archive)}` | {_cell(parts)} |")
    return "\n".join(lines) + "\n"


def render_includes(text: str, root: pathlib.Path,
                    seen: tuple[str, ...] = ()) -> str:
    """Expand every `--8<-- "path"` line with the file at that path.

    Paths are repo-root-relative. Includes nest; a cycle fails instead
    of recursing, and a missing file fails instead of rendering half
    a README. The included text joins as lines, so blank lines around
    an include stay the including file's decision.
    """
    out = []
    for line in text.splitlines():
        match = _INCLUDE_RE.match(line)
        if not match:
            out.append(line)
            continue
        path = match.group(2)
        if path in seen:
            raise DocsGenError(
                f"include cycle: {' -> '.join([*seen, path])}")
        target = root / path
        if not target.is_file():
            raise DocsGenError(f"include not found: {path}")
        out.append(render_includes(
            target.read_text(), root, (*seen, path)).rstrip("\n"))
    return "\n".join(out) + "\n"


def generate(root: pathlib.Path) -> dict[str, str]:
    """The rendered outputs keyed by repo-relative path."""
    manifest = epicmanifest.load(root / "common" / "manifest"
                                 / "modules.toml")
    try:
        src = (root / "docs" / "README.src.md").read_text()
    except OSError:
        raise DocsGenError("docs/README.src.md missing;"
                           " restore it, README.md renders from it") from None
    rendered, _ = readme_tables.regenerate(render_includes(src, root))
    outputs = {
        "docs/reference/modules.md": emit_modules_md(manifest),
        "docs/reference/families.md": emit_families_md(manifest),
        f"{USER_DIR}/index.md": emit_user_index_md(manifest),
        "docs/reference/packs.md": emit_packs_md(manifest),
        "README.md": rendered,
    }
    for name in user_modules(manifest):
        page = _page_name(manifest.modules[name])
        outputs[f"{USER_DIR}/modules/{page}.md"] = emit_user_module_md(
            manifest, name)
    return outputs


def orphan_pages(root: pathlib.Path, outputs: dict[str, str]) -> list[str]:
    """Pages under docs/user that no module generates any more."""
    found = (p.relative_to(root).as_posix()
             for p in (root / USER_DIR).rglob("*.md"))
    return sorted(p for p in found if p not in outputs)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate the HAL reference pages and render README.md.")
    parser.add_argument("--check", action="store_true",
                        help="fail on a stale page instead of writing it")
    args = parser.parse_args()
    root = pathlib.Path(__file__).resolve().parents[2]
    problems = shared_includes.check(root)
    if problems:
        for problem in problems:
            print(f"docs_gen: {problem}", file=sys.stderr)
        return 1
    try:
        outputs = generate(root)
    except DocsGenError as exc:
        print(f"docs_gen: {exc}", file=sys.stderr)
        return 2
    stale = [p for p, text in outputs.items()
             if not (root / p).is_file() or (root / p).read_text() != text]
    orphans = orphan_pages(root, outputs)
    stale += orphans
    if args.check:
        if stale:
            print(f"docs_gen: stale: {', '.join(stale)};"
                  " run make docs-gen to regenerate", file=sys.stderr)
            return 1
        return 0
    for path in orphans:
        (root / path).unlink()
    for path, text in outputs.items():
        (root / path).parent.mkdir(parents=True, exist_ok=True)
        (root / path).write_text(text)
    for path in stale:
        print(f"docs_gen: regenerated {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
